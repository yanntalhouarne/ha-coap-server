#!/usr/bin/env python3
"""Builds and runs the firmware unit tests on this PC.

Each tests/unit/test_*.c file includes one firmware source file and is compiled, with
fake Zephyr and OpenThread headers (tests/unit/fakes), into its own program. The
CONFIG_ values are the firmware's own: the defaults in application/Kconfig, overridden
by application/prj.conf.

Needs a C compiler: the one in $CC, else cc, gcc or clang, else Zig's
(`pip install ziglang`), which works on Windows, macOS and Linux.

Usage: python application/tests/unit/run.py [--sanitize] [test name ...]
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent.parent

# Kconfig symbols that come from Zephyr templates rather than application/Kconfig
EXTRA_CONFIG = {
    "CONFIG_COAP_SERVER_LOG_LEVEL": "3",
    "CONFIG_COAP_RESOURCES_LOG_LEVEL": "3",
}

KCONFIG_KEYWORDS = ("config", "menuconfig", "menu", "endmenu", "choice", "endchoice", "if", "endif",
                    "source", "module", "module-str", "comment", "mainmenu")


def kconfig_defaults(path):
    """Returns {CONFIG_NAME: value} for the first default of each symbol in a Kconfig file,
    and 1 for the default of each choice."""
    values = {}
    symbol = None
    in_choice = False
    in_help = False
    for line in path.read_text(encoding="utf-8").splitlines():
        text = line.strip()
        word = text.split(maxsplit=1)[0] if text else ""
        if in_help:
            if word not in KCONFIG_KEYWORDS:
                continue
            in_help = False
        if word in ("config", "menuconfig"):
            symbol = text.split()[1]
        elif word == "choice":
            in_choice, symbol = True, None
        elif word == "endchoice":
            in_choice, symbol = False, None
        elif word in KCONFIG_KEYWORDS:
            symbol = None
        elif word == "help":
            in_help = True
        elif word == "default":
            value = text.split(maxsplit=1)[1]
            if symbol is None and in_choice:
                values["CONFIG_" + value] = "1"
            elif symbol is not None and "CONFIG_" + symbol not in values:
                if value == "y":
                    value = "1"
                if value != "n":
                    values["CONFIG_" + symbol] = value
    return values


def conf_values(path):
    """Returns {CONFIG_NAME: value} from a .conf file; =n removes the symbol (None)."""
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"\s*(CONFIG_\w+)\s*=\s*(.*?)\s*$", line)
        if match:
            name, value = match.groups()
            values[name] = None if value == "n" else ("1" if value == "y" else value)
    return values


def write_config_header(path):
    values = dict(EXTRA_CONFIG)
    values.update(kconfig_defaults(APP / "Kconfig"))
    values.update(conf_values(APP / "prj.conf"))
    lines = ["/* Generated by tests/unit/run.py from application/Kconfig and prj.conf */"]
    lines += [f"#define {name} {value}" for name, value in sorted(values.items()) if value is not None]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def find_compiler():
    if os.environ.get("CC"):
        return os.environ["CC"].split()
    for name in ("cc", "gcc", "clang"):
        if shutil.which(name):
            return [name]
    try:
        import ziglang  # noqa: F401
        return [sys.executable, "-m", "ziglang", "cc"]
    except ImportError:
        sys.exit("No C compiler found. Install gcc or clang, or run: python -m pip install ziglang")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--sanitize", action="store_true",
                        help="build with AddressSanitizer and UndefinedBehaviorSanitizer (gcc or clang on Linux/macOS)")
    parser.add_argument("tests", nargs="*", help="tests to run, for example test_pump (default: all)")
    args = parser.parse_args()

    tests = sorted(HERE.glob("test_*.c"))
    if args.tests:
        tests = [t for t in tests if t.stem in args.tests or t.name in args.tests]
        if not tests:
            sys.exit("No such test: " + ", ".join(args.tests))

    compiler = find_compiler()
    flags = ["-std=gnu11", "-g", "-Wall", "-Werror", "-Wno-unused-function"]
    if args.sanitize:
        flags += ["-fsanitize=address,undefined", "-fno-sanitize-recover=all"]

    failed = []
    with tempfile.TemporaryDirectory(prefix="hacoap-unit-") as tmp:
        tmp = Path(tmp)
        config = tmp / "config.h"
        write_config_header(config)
        for test in tests:
            exe = tmp / (test.stem + (".exe" if os.name == "nt" else ""))
            command = compiler + flags + [
                "-include", str(config),
                "-I", str(HERE / "fakes"), "-I", str(HERE), "-I", str(APP / "include"),
                str(test), str(HERE / "fakes" / "fakes.c"), "-o", str(exe),
            ]
            print(f"== {test.stem}", flush=True)
            if subprocess.run(command).returncode != 0:
                print(f"FAIL {test.stem}: does not compile")
                failed.append(test.stem)
                continue
            if subprocess.run([str(exe)]).returncode != 0:
                failed.append(test.stem)

    print()
    if failed:
        print("Failed: " + ", ".join(failed))
        return 1
    print(f"All {len(tests)} test programs passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
